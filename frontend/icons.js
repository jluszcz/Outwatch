// One glyph, sized in em so it rides its button's font-size, and painted with
// currentColor so it inherits the button's colour — including the red the
// delete item takes on hover — without a token of its own. Always aria-hidden:
// every caller labels the control it sits in.
export function Icon({ name, filled }) {
    const icon = ICONS[name];
    const paths = (filled && icon.fill) || icon.outline;
    return html`<svg
        class="bi"
        viewBox="0 0 16 16"
        fill="currentColor"
        aria-hidden="true"
        focusable="false"
    >
        ${paths.map((d, i) => html`<path key=${i} d=${d} />`)}
    </svg>`;
}
